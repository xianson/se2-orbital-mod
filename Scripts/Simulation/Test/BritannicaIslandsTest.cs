namespace OrbitalMod;

/// <summary>
/// Britannica (2026-10-26): its own planet now (definitions in Assets/Procedural/Planets/BritannicaFloor, spawned into a
/// world once by the dev `spawnplanet`) - no ground (its generator sinks the surface to a 42 km core), only sky islands over the whole planet (<see cref="BritannicaLayout"/>, <see cref="BritannicaWorld"/>):
/// <see cref="BritannicaIsland"/> shapes added to the planet's own voxel composition through
/// <see cref="ProcShapeBridge"/>, on the server's planet (collision) and the client's (what is drawn), each with its
/// biome's materials resolved to that planet's storage indices. Nothing is saved: they come back on every load of the
/// world that has Britannica (any other planet is untouched).
/// Called from BritannicaCutTest.Tick (server) and .ClientTick (client).
/// </summary>
public static class BritannicaIslandsTest
{
    public static bool Enabled = true;
    public static string ServerStatus = "-", ClientStatus = "-";
    public static int Count, Outside;   // (the last side's, for status; each attach counts in its own locals - the server and
                                        //  client attach at once on two threads: a shared counter read 1650 and 3358 for 2058)
    // (the islands: BritannicaSea, generated by tools/britannica/build_sea.py)
    /// <summary>Britannica's server prefab (britannica_guids.json) and the game's planet-spawner configurator prefab.</summary>
    public static readonly Guid ServerPrefab = new("23807eee-d27a-4a52-9f2a-e7d56be9a145"), SpawnerPrefab = new("747b5ac6-eab5-414c-95b4-a79e0d5fa34b");

    /// <summary>Britannica's planet entity (server beacon or client frame), by its entity name ("Britannica": its prefabs'
    /// DebugName). Not by composition Guid: the Orbital Mod's injection gives planet entities a runtime composition of
    /// their own - that test matched nothing (2026-10-26). (The "wrong planet" it was meant to stop was Britannica itself:
    /// the dev spawn had worked despite its exception.)</summary>
    internal static bool IsBritannica(Keen.VRage.DCS.Components.Entity e) => e.DebugName != null && e.DebugName.Contains("Britannica", StringComparison.OrdinalIgnoreCase);

    sealed class Side { public Keen.VRage.Core.Game.Systems.Session Session; public object Planet; public bool Added; public int Retries, Look; }
    static readonly Side _server = new Side(), _client = new Side();

    public static void Tick(Keen.VRage.Core.Game.Systems.Session session, bool server)
    {
        if (!Enabled || session == null) return;
        var s = server ? _server : _client;
        if (!ReferenceEquals(session, s.Session)) { s.Session = session; s.Planet = null; s.Added = false; s.Retries = 0; }
        try
        {
            if (s.Added)
            {
                // (the planet processes added shapes only while its checkpoint is open: retry until the queue is empty)
                if (s.Retries > 0 && s.Retries < 600)
                {
                    int q = ProcShapeBridge.Queued(s.Planet);
                    if (q > 0) { ProcShapeBridge.Signal(s.Planet); s.Retries++; }
                    else { Set(server, $"{Count} islands in Britannica's composition (after {s.Retries} retries)"); s.Retries = 0; }
                }
                return;
            }
            if (s.Look++ % 120 != 0) return;   // (a world without Britannica: looked for every ~2 s, not every tick)
            object planet = null;
            if (server) { foreach (var e in session.GetEntitiesOfType<ServerPlanetBeacon>()) if (IsBritannica(e)) { planet = e; break; } }
            else { foreach (var e in session.GetEntitiesOfType<PlanetFrameComponent>()) if (IsBritannica(e)) { planet = e; break; } }
            if (planet == null) return;   // (not in the scene yet: next tick)
            s.Planet = planet; s.Added = true;
            Vector3 center = ProcShapeBridge.PlanetCenter(planet);
            // the biomes' palettes as this planet's storage indices (a material it lacks falls back to the next one)
            var palettes = new Dictionary<BritannicaPaint.Type, byte[]>();
            var missing = new List<string>();
            foreach (BritannicaPaint.Type b in Enum.GetValues(typeof(BritannicaPaint.Type)))
            {
                var guids = BritannicaPaint.Palette(b);
                var pal = guids.Select(g => ProcShapeBridge.MaterialIndex(planet, g)).ToArray();
                for (int i = 0; i < pal.Length; i++) if (pal[i] == 255) { missing.Add($"{b}[{i}]"); pal[i] = pal.FirstOrDefault(v => v != 255, (byte)255); }
                palettes[b] = pal;
            }
            var sw = System.Diagnostics.Stopwatch.StartNew();
            long tLayout = sw.ElapsedMilliseconds;
            var sb = new System.Text.StringBuilder("# dirX dirY dirZ top radius depth crack type satellite (planet frame; top = radius from the centre, m)\n");
            int count = 0, outside = 0;
            // (both sides: straight into the composition, no checkpoint - its notifications made the voxel physics sweep
            //  every physics-chunk coordinate in each island's box: 91 s on the server, then the same 90 s on the client's
            //  main thread when the game's own checkpoint processed the queue (planeteditor's traces, 2026-10-26). At attach
            //  no cell near Britannica is built yet. Known gap: render cells built BEFORE the attach (the planet seen from
            //  afar) keep their old look until they rebuild)
            var direct = new List<ProcShape>();
            // (the authored island sea - tools/britannica/build_sea.py: its layout and real-terrain tops)
            for (int i = 0; i < BritannicaSea.Count; i++)
            {
                var type = BritannicaSea.Type[i]; float r = BritannicaSea.Radius[i], top = BritannicaSea.Top[i];
                bool sat = BritannicaSea.Satellite[i];
                float depth = BritannicaSea.DepthOf(i);
                BritannicaSea.Maps(i, out var gh, out var gd);
                Vector3 dir = BritannicaSea.DirOf(i);
                var isl = new BritannicaIsland
                {
                    Radius = r, Depth = depth, PlateSize = Math.Clamp(r * 0.6f, 40f, 1900f), CrackWidth = 0, PlateStep = sat ? 6 : 30,
                    Seed = i * 7919 + 13, Biome = type == BritannicaPaint.Type.Burnt ? BritannicaBiomes.Biome.Burnt : BritannicaBiomes.Biome.Savanna,
                    Palette = palettes[type], Rim = BritannicaSea.RimOf(i), Grid = gh, Sdf = gd, GridN = BritannicaSea.GridN[i], GridStep = BritannicaSea.Step[i],
                }.Init(center, dir * top);
                // (only islands wholly inside the storage cube [0, 2 x Center]: outside it there are no voxels)
                if (Vector3.Min(isl.Box.Min, Vector3.Zero) != Vector3.Zero || Vector3.Max(isl.Box.Max, center * 2) != center * 2) { outside++; continue; }
                direct.Add(isl);
                count++;
                sb.AppendLine(FormattableString.Invariant($"{dir.X:F6} {dir.Y:F6} {dir.Z:F6} {top:F0} {r:F0} {depth:F0} 0 {type} {(sat ? 1 : 0)}"));
            }
            ProcShapeBridge.AddDirect(planet, direct);
            long tAdd = sw.ElapsedMilliseconds;
            ProcShapeBridge.Signal(planet);   // (once, for all of them)
            long tSignal = sw.ElapsedMilliseconds;
            if (server)
                try
                {
                    string dir = System.IO.Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "OrbitalPlanets", "Britannica");
                    System.IO.Directory.CreateDirectory(dir);
                    System.IO.File.WriteAllText(System.IO.Path.Combine(dir, "islands_layout.txt"), sb.ToString());
                }
                catch { }
            string pals = string.Join(" ", palettes.Select(kv => $"{kv.Key}=" + string.Join(",", kv.Value)));
            int queued = ProcShapeBridge.Queued(planet);
            Count = count; Outside = outside;
            string head = $"{count} islands ({outside} skipped: outside the storage) in {tSignal} ms (layout {tLayout}, add {tAdd - tLayout} - {direct.Count} direct, signal {tSignal - tAdd}); palettes {pals}" + (missing.Count > 0 ? "; missing " + string.Join(" ", missing) : "");
            if (queued > 0) { s.Retries = 1; Set(server, head + $"; {queued} waiting for the planet's checkpoint"); }
            else Set(server, head + "; in Britannica's composition");
        }
        catch (Exception ex)
        {
            s.Added = true;
            var inner = ex is System.Reflection.TargetInvocationException t && t.InnerException != null ? t.InnerException : ex;
            Set(server, "failed: " + inner.GetType().Name + ": " + inner.Message);
        }
    }

    static void Set(bool server, string status, bool say = true)
    {
        if (server) ServerStatus = status; else ClientStatus = status;
        if (say) Log.Default.WriteLine($"[BRITANNICA-ISLANDS] {(server ? "server" : "client")}: {status}");
    }
}
